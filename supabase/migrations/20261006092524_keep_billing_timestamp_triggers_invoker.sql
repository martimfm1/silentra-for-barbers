-- Keep billing timestamp triggers non-privileged while pinning search_path.

create or replace function public.touch_platform_settings_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

